// A faster drop-in for makefun-site 1.0.0 (the reference program of
// site-generator-speed-01-run-20261122). run(input) returns exactly the output tree makefun-site 1.0.0's build
// returns for the input, byte for byte. Same rules as the reference (its README.md states them; its code is the
// reference wherever the two differ), reimplemented for speed:
//
// - Markdown is lexed and rendered in one pass, straight into the output string: no token objects, no block
//   arrays, and inline markup is scanned with plain-text runs escaped in bulk instead of one escape call per
//   character.
// - slugify takes an ASCII fast path (NFKD is the identity on ASCII) and its results are cached per build.
// - Front matter is found by scanning for its closing line instead of splitting the whole body.
// - Templates are parsed once per build and rendered by a tight interpreter; a template whose free variables
//   are only site/tags/recent (and no loop anywhere in the case binds those names) is rendered once per
//   (template, include depth) and reused: head/header/footer fragments are the same on every page.
// - Word counting counts without allocating the word list.
//
// Nothing is cached from one case to the next: every per-build cache is created fresh inside run().

